package Aula_08_10_2026;

public class Animal {
	String nome;
	String cor;
	String tamanho;
	String peso;
	String raca;
	public String getNome() {
		return nome;
	}
	public void setNome(String nome) { // Serve para você futuramente setar/definir o atributo
		this.nome = nome;
	}
	public String getCor() {
		return cor;
	}
	public void setCor(String cor) {
		this.cor = cor;
	}
	public String getTamanho() {
		return tamanho;
	}
	public void setTamanho(String tamanho) {
		this.tamanho = tamanho;
	}
	public String getPeso() {
		return peso;
	}
	public void setPeso(String peso) {
		this.peso = peso;
	}
	public String getRaca() {
		return raca;
	}
	public void setRaca(String raca) {
		this.raca = raca;
	}
}
